/** KST 기준 오늘 공개된 챕터만 반환 */
export function getReleasedChapters(now = new Date()): BibleChapter[] {
  const kstToday = getKstDateString(now);
  return BIBLE_CHAPTERS.filter((chapter) => chapter.releaseDate <= kstToday);
}

/** 다음 공개 예정 챕터 */
export function getNextChapter(now = new Date()): BibleChapter | null {
  const kstToday = getKstDateString(now);
  return BIBLE_CHAPTERS.find((chapter) => chapter.releaseDate > kstToday) ?? null;
}

export function getBibleChapter(slug: string): BibleChapter | undefined {
  return BIBLE_CHAPTERS.find((chapter) => chapter.slug === slug);
}

/** 공개된 챕터인지 확인 (미공개 챕터는 상세 페이지 접근 불가) */
export function isChapterReleased(chapter: BibleChapter, now = new Date()): boolean {
  return chapter.releaseDate <= getKstDateString(now);
}

function getKstDateString(date: Date): string {
  return new Date(date.getTime() + 9 * 60 * 60 * 1000).toISOString().slice(0, 10);
}
